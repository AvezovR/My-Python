# Усовершенствуйте старую программу:
#
# У нас есть список из трёх слов, которые вводит пользователь. Затем вводится сам текст произведения, который вводится
# уже в одну строку. Напишите программу, которая посчитает, сколько раз слова пользователя встречаются в тексте.
# Однажды Лебедь, Рак, да Щука, Лебедь рвётся в облака, Рак пятится назад, а Щука тянет в воду.
# Лебедь Рак Щука
import re
world_lst = input('Введите три слова через пробел: ').split()

work_text_str = input('Введите текст произведения: ')
work_text = re.findall(r"\w+", work_text_str)

for word in world_lst:
    count_word = work_text.count(word)
    print(f'Слово "{word}" встречается в тексте {count_word} раз(a)')
